// Solves the web UI's Groundwork theme, web/src/theme/triage.json, into light,
// dark and Darker, and the issue states' tones against it and Snag, into
// web/src/theme/themes.generated.css, so the browser never solves a built-in
// theme, and writes the script that applies the stored pick before the first
// paint into web/src/theme/boot.generated.js. Fails when a role misses its
// contrast target. With --check it writes nothing and fails if either file is
// out of date.
import { BunRuntime, BunServices } from "@effect/platform-bun";
import snag from "@timmo001/groundwork-tokens/themes/snag.json" with { type: "json" };
import {
  appTones,
  parseTheme,
  runtimeTheme,
} from "@timmo001/groundwork-tokens/runtime";
import { themeBootScript } from "@timmo001/groundwork-tokens/page";
import { Effect, FileSystem, Predicate, Schema } from "effect";
import { themeOptions } from "../web/src/theme/options.ts";
import { stateTones } from "../web/src/theme/tones.ts";

const themeFile = "web/src/theme/triage.json";

const cssFile = "web/src/theme/themes.generated.css";

const bootFile = "web/src/theme/boot.generated.js";

const check = process.argv.includes("--check");

class ThemeError extends Schema.TaggedError<ThemeError>()("ThemeError", {
  message: Schema.String,
}) {}

// The tokens package has its own effect, so its Result is read by its tag
// rather than passed to this one's Result helpers
const decode = (text: string, name: string) => {
  const parsed = parseTheme(text);

  return Predicate.isTagged(parsed, "Failure")
    ? Effect.fail(
        new ThemeError({
          message: `${name} isn't a theme: ${String(parsed.failure)}`,
        }),
      )
    : Effect.succeed(parsed.success);
};

const program = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const triage = yield* decode(yield* fs.readFileString(themeFile), themeFile);

  const { css, checks } = runtimeTheme(triage);
  const misses = checks.filter((result) => !result.passes);

  if (misses.length > 0) {
    return yield* new ThemeError({
      message: `The Triage theme misses contrast targets: ${misses.map((miss) => `${miss.role} in ${miss.mode} (${miss.ratio.toFixed(2)})`).join(", ")}`,
    });
  }

  // Snag's JSON import is typed loosely, so it's decoded like the Triage theme
  const snagTheme = yield* decode(JSON.stringify(snag), "Groundwork's Snag");

  const tones = appTones(stateTones, [triage, snagTheme]);

  const files = [
    [
      cssFile,
      `/* Generated by scripts/generate-theme.ts from ${themeFile}. Don't edit. */\n${css}\n\n${tones}\n`,
    ],
    [
      bootFile,
      `// Generated by scripts/generate-theme.ts. Don't edit.\n// Applies the stored theme and mode before the first paint.\n${themeBootScript(themeOptions)}\n`,
    ],
  ] as const;

  const stale: Array<string> = [];

  for (const [file, next] of files) {
    const current = yield* fs
      .readFileString(file)
      .pipe(Effect.orElseSucceed(() => ""));

    if (next !== current) {
      stale.push(file);

      if (!check) {
        yield* fs.writeFileString(file, next);
      }
    }
  }

  if (check) {
    if (stale.length > 0) {
      return yield* new ThemeError({
        message: `${stale.join(", ")} out of date with ${themeFile}. Run \`mise run theme:gen\`.`,
      });
    }

    yield* Effect.log("The web UI's theme is up to date");

    return;
  }

  yield* Effect.log(
    `Wrote the Triage theme: all ${checks.length} contrast checks pass`,
  );
});

program.pipe(Effect.provide(BunServices.layer), BunRuntime.runMain);
